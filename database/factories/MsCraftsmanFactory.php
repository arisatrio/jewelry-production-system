<?php

namespace Database\Factories;

use App\Models\MsCraftsman;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<MsCraftsman>
 */
class MsCraftsmanFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'name' => fake()->unique()->name(),
            'rate' => null,
            'is_active' => 'YES',
            'employee_id' => null,
            'user_id' => null,
            'is_deleted' => 0,
            'created_date' => now(),
            'created_by' => 'system',
            'modified_date' => now(),
            'modified_by' => 'system',
            'deleted_date' => null,
            'deleted_by' => null,
        ];
    }

    /**
     * Indicate that the craftsman is soft-deleted.
     */
    public function deleted(): static
    {
        return $this->state(fn (array $attributes): array => [
            'is_deleted' => 1,
            'deleted_date' => now(),
            'deleted_by' => 'system',
        ]);
    }
}
